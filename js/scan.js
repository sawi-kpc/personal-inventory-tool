function renderScan(){
  return `<h2 class="section-title">Scan code</h2>
  <div class="scan-view">
    <div class="scan-frame" id="scanFrame">
      <video id="scanVideo" playsinline muted></video>
      <canvas id="scanCanvas" style="display:none;"></canvas>
    </div>
    <p class="scan-hint" id="scanStatus">Opening camera...</p>
    <p style="font-size:12px;color:var(--ink-faint);">If the camera doesn't open, try uploading a photo of the QR instead.</p>
    <input type="file" id="qrImageInput" accept="image/*" style="display:none" onchange="handleQrImageUpload(this)">
    <button class="btn btn-outline" onclick="document.getElementById('qrImageInput').click()">Upload QR photo</button>
    <label class="field" style="margin-top:16px;text-align:left;"><span class="lbl">Or type the code printed on the sticker</span><input type="text" id="manualCodeInput" placeholder="e.g. k3n8x2p" onkeydown="if(event.key==='Enter') handleManualCode()"></label>
    <button class="btn btn-secondary" onclick="handleManualCode()">Look up code</button>
  </div>`;
}
function handleManualCode(){
  const v = document.getElementById('manualCodeInput').value.trim().toLowerCase();
  if(!v) return;
  handleScanResult(v);
}
let scanPausedUntil = 0; // decoding is skipped until this timestamp (ms)
function setScanStatus(msg){
  const s = document.getElementById('scanStatus');
  if(s) s.textContent = msg;
}
async function startScan(){
  const video = document.getElementById('scanVideo');
  if(!video) return;
  stopScan();
  scanPausedUntil = 0;
  let stream;
  try{
    // Higher resolution helps with small labels; 'ideal' falls back gracefully
    stream = await navigator.mediaDevices.getUserMedia({video:{
      facingMode:'environment', width:{ideal:1920}, height:{ideal:1080}
    }});
    // Continuous autofocus where supported (ignored otherwise)
    try{ await stream.getVideoTracks()[0].applyConstraints({advanced:[{focusMode:'continuous'}]}); }catch(_){}
    if(currentTab!=='scan' || !document.getElementById('scanVideo')){
      stream.getTracks().forEach(t=>t.stop()); return; // user left the tab while the camera was starting
    }
    scanStream = stream;
    video.srcObject = stream;
    await video.play();
  }catch(e){
    if(stream && stream!==scanStream) stream.getTracks().forEach(t=>t.stop());
    setScanStatus('Could not open camera (' + (e.name||'error') + '). Allow camera access, or upload a photo instead.');
    return;
  }
  setScanStatus('Point the camera at the QR code');
  scanLoop();
}
function scanLoop(){
  const video = document.getElementById('scanVideo');
  const canvas = document.getElementById('scanCanvas');
  if(!video || !canvas || currentTab!=='scan') return;
  // Schedule the next frame first so one failed frame can't end scanning
  scanRAF = requestAnimationFrame(scanLoop);
  if(video.readyState !== video.HAVE_ENOUGH_DATA || !video.videoWidth) return;
  if(scanPausedUntil){
    if(Date.now() < scanPausedUntil) return;
    scanPausedUntil = 0;
    setScanStatus('Point the camera at the QR code');
  }
  try{
    if(canvas.width!==video.videoWidth) canvas.width = video.videoWidth;
    if(canvas.height!==video.videoHeight) canvas.height = video.videoHeight;
    const ctx = canvas.getContext('2d', {willReadFrequently:true});
    ctx.drawImage(video,0,0,canvas.width,canvas.height);
    const imgData = ctx.getImageData(0,0,canvas.width,canvas.height);
    const code = jsQR(imgData.data, imgData.width, imgData.height, {inversionAttempts:'dontInvert'});
    if(code && code.data) handleScanResult(code.data);
  }catch(e){
    // Shown so a decode problem is not mistaken for a camera problem
    setScanStatus('Scan error: ' + (e.name||'') + ' ' + (e.message||''));
  }
}
function stopScan(){
  if(scanRAF) cancelAnimationFrame(scanRAF);
  if(scanStream){ scanStream.getTracks().forEach(t=>t.stop()); scanStream=null; }
}
function handleScanResult(data){
  const id = data.startsWith('INVQR:') ? data.slice(6) : data;
  const item = items.find(i=>i.id===id);
  if(!item){
    // Keep the camera running (restarting it flashes a black frame); just
    // pause decoding briefly so the message can be read.
    setScanStatus(`Read "${id}" — this code wasn't generated by this system, no match found.`);
    scanPausedUntil = Date.now() + 2000;
    return;
  }
  stopScan();
  if(item.unassigned){
    // Not filled in yet -> go fill in the item's data
    editingId = id; capturedPhoto = null; addMode = 'form'; formReturnTo = 'hub';
    switchTab('add');
  } else {
    // Already has data -> go straight to stock adjustment (detail view has the quantity actions)
    switchTab('list'); openDetail(item.id);
  }
}
function handleQrImageUpload(input){
  const file = input.files[0];
  if(!file) return;
  const reader = new FileReader();
  reader.onload = e=>{
    const img = new Image();
    img.onload = ()=>{
      const canvas = document.createElement('canvas');
      canvas.width = img.width; canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(img,0,0);
      const imgData = ctx.getImageData(0,0,canvas.width,canvas.height);
      const code = jsQR(imgData.data, imgData.width, imgData.height);
      if(code && code.data) handleScanResult(code.data);
      else alert("Couldn't read a QR code from that photo. Try another one.");
    };
    img.src = e.target.result;
  };
  reader.readAsDataURL(file);
}
